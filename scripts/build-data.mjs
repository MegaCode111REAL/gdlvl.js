// Regenerates the JS data modules from the files in data/:
//   data/schema.json       -> src/schema-data.js   (classes, properties, types, object ID -> class)
//   data/object-names.txt  -> src/names-data.js    (object ID -> name; alternating "id" / "name" lines)
// Run after replacing either source file:  npm run build:data
// (The data is wrapped in JS modules so it imports the same way in Node 18+, browsers and bundlers,
// without needing JSON import attributes.)
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const banner = (from) =>
  `// GENERATED by scripts/build-data.mjs from ${from}. Do not edit by hand.\n` +
  "// Data: GD Info Explorer (https://flowvix.github.io/gd-info-explorer/), see NOTICE.md.\n";

// ---- schema
const schema = JSON.parse(readFileSync(new URL("data/schema.json", root), "utf8"));
for (const k of ["types", "classes", "idClasses", "defaultClass"])
  if (!(k in schema)) throw new Error(`data/schema.json is missing "${k}"`);
writeFileSync(new URL("src/schema-data.js", root), banner("data/schema.json") + "export default " + JSON.stringify(schema) + ";\n");
console.log(`schema: ${Object.keys(schema.classes).length} classes, ${Object.keys(schema.idClasses).length} mapped object IDs`);

// ---- object names
const lines = readFileSync(new URL("data/object-names.txt", root), "utf8").split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
if (lines.length % 2) throw new Error("data/object-names.txt must have an even number of non-empty lines (id, name, id, name, ...)");
const names = {};
for (let i = 0; i < lines.length; i += 2) {
  const [id, name] = [lines[i], lines[i + 1]];
  if (!/^\d+$/.test(id)) throw new Error(`object-names.txt: expected an ID at entry ${i / 2 + 1}, got "${id}"`);
  if (id in names) throw new Error(`object-names.txt: duplicate ID ${id}`);
  names[id] = name;
}
writeFileSync(new URL("src/names-data.js", root), banner("data/object-names.txt") + "export default " + JSON.stringify(names) + ";\n");
console.log(`names: ${Object.keys(names).length} objects`);

const unnamed = Object.keys(schema.idClasses).filter((id) => !(id in names));
if (unnamed.length) console.warn(`warning: ${unnamed.length} schema-mapped IDs have no name, e.g. ${unnamed.slice(0, 5).join(", ")}`);
