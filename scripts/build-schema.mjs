// Regenerates src/schema-data.js from data/schema.json.
// Run after replacing data/schema.json with a newer export:  node scripts/build-schema.mjs
// (The data is wrapped in a JS module so it imports the same way in Node 18+, browsers and bundlers,
// without needing JSON import attributes.)
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("data/schema.json", root), "utf8"));

for (const k of ["types", "classes", "idClasses", "defaultClass"])
  if (!(k in schema)) throw new Error(`data/schema.json is missing "${k}"`);

const banner =
  "// GENERATED by scripts/build-schema.mjs from data/schema.json. Do not edit by hand.\n" +
  "// Data: GD Info Explorer (https://flowvix.github.io/gd-info-explorer/), see NOTICE.md.\n";
writeFileSync(new URL("src/schema-data.js", root), banner + "export default " + JSON.stringify(schema) + ";\n");
console.log(`wrote src/schema-data.js: ${Object.keys(schema.classes).length} classes, ${Object.keys(schema.idClasses).length} mapped object IDs`);
